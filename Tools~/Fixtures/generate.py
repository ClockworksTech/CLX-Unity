#!/usr/bin/env python3
"""Regenerates the wire fixtures from the real Go and Rust encoders.

    generate.py            Runs both generators, then writes WireFixtures.cs.
    generate.py --go-only  Keeps rust.txt, for when Rust can't build right now.

Needs Go and Cargo, and works offline if their module caches have the
dependencies. go.txt, rust.txt and Tests/Editor/WireFixtures.cs are committed, so
running the tests needs neither.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
output = here.parent.parent / "Tests" / "Editor" / "WireFixtures.cs"


def run_go():
    result = subprocess.run(
        ["go", "run", "."],
        cwd=here / "go",
        env={**os.environ, "GOFLAGS": "-mod=mod", "GOPROXY": "off", "GONOSUMDB": "*"},
        capture_output=True, text=True, check=True,
    )
    (here / "go.txt").write_text(result.stdout)


def run_rust():
    result = subprocess.run(
        ["cargo", "run", "--quiet", "--offline", "--target-dir", str(here / "rust" / "target")],
        cwd=here / "rust",
        capture_output=True, text=True, check=True,
    )
    (here / "rust.txt").write_text(result.stdout)


def fields(prefix, text):
    single, arrays = {}, {}
    for line in text.splitlines():
        if line.startswith("#"):
            continue
        name, data = line.split("\t")
        match = re.fullmatch(r"(\w+)\[(\d+)\]", name)
        if match:
            arrays.setdefault(match[1], []).append(data)
        else:
            single[name] = data

    out = []
    for name, data in single.items():
        out.append(f'        public const string {rename(prefix, name)} = "{data}";')
        out.append("")
    for name, items in arrays.items():
        out.append(f"        public static readonly string[] {rename(prefix, name)} =")
        out.append("        {")
        out.extend(f'            "{item}",' for item in items)
        out.append("        };")
        out.append("")
    return out


def rename(prefix, name):
    for special in ("Prolink", "Viewer"):
        if name.startswith(special):
            return name
    if name.startswith("Leader"):
        return "Viewer" + name
    return prefix + name


def main():
    run_go()
    if "--go-only" not in sys.argv:
        run_rust()

    lines = [
        "// Generated by Tools~/Fixtures/generate.py. Don't edit by hand.",
        "//",
        "// Datagrams with the senders' struct shapes, from the msgpack libraries they",
        "// really use (Go vmihailenco/msgpack and Rust rmp_serde). If rust.txt starts",
        "// with a comment saying so, its bytes are a hand-encoded stand-in for now.",
        "// Go* is Clockworks Server, Prolink* is prolink-clx, Rust* is the Bridge and",
        "// Viewer* is what ClockworksViewer3 transmits itself.",
        "namespace Clockworks.CLX.Tests",
        "{",
        "    public static class WireFixtures",
        "    {",
        '        public const string Title = "Déjà Vu (Extended Mix)";',
        "",
    ]
    body = fields("Go", (here / "go.txt").read_text()) + fields("Rust", (here / "rust.txt").read_text())
    lines += body[:-1]
    lines += ["    }", "}", ""]
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {output} ({output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
